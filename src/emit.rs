//! Emission of plain Rust from a loaded project, with a source map back to
//! the `.lrs` files.

use crate::lexer::Kind;
use crate::model::*;
use crate::resolve::*;

#[derive(Clone, Debug)]
pub struct MapEntry {
    pub out: usize,
    pub out_len: usize,
    pub file: usize,
    pub src: usize,
    pub src_len: usize,
    /// verbatim copy (offsets map 1:1) vs. generated text (maps to a fixed span)
    pub linear: bool,
}

#[derive(Clone, Default, Debug)]
pub struct SourceMap {
    pub entries: Vec<MapEntry>,
}

impl SourceMap {
    /// Map the start of an output span to (file, source offset).
    pub fn start(&self, off: usize) -> Option<(usize, usize)> {
        let i = self.entries.partition_point(|e| e.out <= off);
        if i == 0 {
            return None;
        }
        let e = &self.entries[i - 1];
        Some((e.file, if e.linear { e.src + (off - e.out).min(e.src_len) } else { e.src }))
    }

    /// Map the (exclusive) end of an output span.
    pub fn end(&self, off: usize) -> Option<(usize, usize)> {
        let i = self.entries.partition_point(|e| e.out < off);
        if i == 0 {
            return None;
        }
        let e = &self.entries[i - 1];
        Some((e.file, if e.linear { e.src + (off - e.out).min(e.src_len) } else { e.src + e.src_len }))
    }
}

pub struct Emitted {
    pub code: String,
    pub map: SourceMap,
    pub diags: Vec<Diag>,
}

/// The public face of a namespace: what other files (and mounts) can see.
#[derive(Clone, Default)]
struct Surface {
    /// every name visible unqualified in the namespace
    names: Vec<String>,
    /// imports generated by the namespace's mounts (first definition wins)
    mounts: Vec<MountImport>,
}

#[derive(Clone)]
struct MountImport {
    prefix: String,
    name: String,
    vis: Vis,
    file: usize,
    start: usize,
    len: usize,
}

struct Em<'a> {
    p: &'a Project,
    out: String,
    map: SourceMap,
    diags: Vec<Diag>,
    surfaces: Vec<Option<Surface>>,
    /// present[file][ns]: does the file contribute to the namespace (or a descendant)?
    present: Vec<Vec<bool>>,
}

/// Output layout:
///
/// * the *canonical* tree (`crate::Foo::Bar`) holds one `pub mod` per namespace and re-exports only
///   the public items of every file, plus whatever the namespace mounts;
/// * every file additionally gets a hidden module tree (`crate::__lrs_f0::Foo::Bar`) holding its
///   real items. A non-`pub` item therefore stays private to the file that defines it.
pub fn emit(p: &Project) -> Emitted {
    let mut present = vec![vec![false; p.nss.len()]; p.files.len()];
    let mut mark = |f: usize, mut id: usize| loop {
        present[f][id] = true;
        match p.nss[id].parent {
            Some(par) => id = par,
            None => break,
        }
    };
    for (id, ns) in p.nss.iter().enumerate() {
        for it in &ns.items {
            mark(it.file, id);
        }
        for &(f, _, _) in &ns.inner_attrs {
            mark(f, id);
        }
    }
    let mut em = Em {
        p,
        out: String::new(),
        map: SourceMap::default(),
        diags: vec![],
        surfaces: vec![None; p.nss.len()],
        present,
    };
    for &(f, a, b) in &p.nss[0].inner_attrs {
        em.range(f, a, b, None);
        em.raw("\n");
    }
    em.emit_canon(0);
    for f in 0..p.files.len() {
        em.emit_file(f);
    }
    Emitted { code: em.out, map: em.map, diags: em.diags }
}

fn path_str(p: &Project, ns: usize) -> String {
    let mut s = String::from("crate");
    for seg in p.ns_path(ns) {
        s.push_str("::");
        s.push_str(&seg);
    }
    s
}

fn file_mod(f: usize) -> String {
    format!("__lrs_f{}", f)
}

/// Path of a namespace inside a file's hidden module tree.
fn file_path_str(p: &Project, f: usize, ns: usize) -> String {
    let mut s = format!("crate::{}", file_mod(f));
    for seg in p.ns_path(ns) {
        s.push_str("::");
        s.push_str(&seg);
    }
    s
}

/// `fn main` in the root must be reachable from the crate root, so it is exported crate-wide.
fn is_root_main(ns: usize, it: &Item) -> bool {
    ns == 0 && it.kind == "fn" && it.name.as_deref() == Some("main") && it.vis == Vis::Priv
}

fn eff_vis(ns: usize, it: &Item) -> Vis {
    if is_root_main(ns, it) {
        Vis::Crate
    } else {
        it.vis
    }
}

impl<'a> Em<'a> {
    fn raw(&mut self, s: &str) {
        self.out.push_str(s);
    }

    fn mapped(&mut self, s: &str, file: usize, src: usize, src_len: usize, linear: bool) {
        if s.is_empty() {
            return;
        }
        self.map.entries.push(MapEntry { out: self.out.len(), out_len: s.len(), file, src, src_len, linear });
        self.out.push_str(s);
    }

    /// Copy source bytes [a, b) of a file verbatim.
    fn copy(&mut self, fid: usize, a: usize, b: usize) {
        if a >= b {
            return;
        }
        let p = self.p;
        let s = &p.files[fid].text[a..b];
        self.mapped(s, fid, a, b - a, true);
    }

    /// Source span (file, start, len) that generated code for an item should point at.
    fn anchor(&self, it: &Item) -> (usize, usize, usize) {
        let f = &self.p.files[it.file];
        let t = f.tokens[it.name_tok.unwrap_or(it.head)];
        (it.file, t.start, t.end - t.start)
    }

    fn surface(&mut self, id: usize) -> Surface {
        if let Some(s) = &self.surfaces[id] {
            return s.clone();
        }
        let p = self.p;
        let ns = &p.nss[id];
        let mut names: Vec<String> = ns.children.iter().map(|(c, _)| c.clone()).collect();
        for it in &ns.items {
            if eff_vis(id, it) != Vis::Priv {
                for n in item_names(it) {
                    names.push(n.to_string());
                }
            }
        }
        let mut taken: std::collections::HashSet<String> = names.iter().cloned().collect();
        let mut mounts = vec![];
        for m in &ns.mounts {
            let Some(t) = ns_by_path(p, &m.path) else {
                self.diags.push(Diag::error(m.file, m.start, m.end, format!("cannot find namespace `.{}`", m.path.join("."))));
                continue;
            };
            let prefix = path_str(p, t);
            for (name, vis) in visible_names(p, t, None) {
                if !taken.insert(name.clone()) {
                    continue; // first definition wins
                }
                names.push(name.clone());
                mounts.push(MountImport { prefix: prefix.clone(), name, vis, file: m.file, start: m.start, len: m.end - m.start });
            }
        }
        let s = Surface { names, mounts };
        self.surfaces[id] = Some(s.clone());
        s
    }

    /// The canonical namespace module: re-exports of public items and mounts.
    fn emit_canon(&mut self, id: usize) {
        let p = self.p;
        let ns = &p.nss[id];
        let anchor = ns.decls.first().map(|d| (d.file, d.header_start, d.name_end - d.header_start));
        if id != 0 {
            let hdr = format!("#[allow(non_snake_case)]\npub mod {} {{\n", ns.name);
            match anchor {
                Some((f, s, l)) => self.mapped(&hdr, f, s, l, false),
                None => self.raw(&hdr),
            }
        }
        for it in &ns.items {
            let vis = eff_vis(id, it);
            if vis == Vis::Priv {
                continue;
            }
            let (f, s, l) = self.anchor(it);
            for name in item_names(it) {
                let line = format!("#[allow(unused_imports)]\n{} {}::{};\n", vis.use_prefix(), file_path_str(p, it.file, id), name);
                self.mapped(&line, f, s, l, false);
            }
        }
        for m in self.surface(id).mounts {
            let line = format!("#[allow(unused_imports)]\n{} {}::{};\n", m.vis.use_prefix(), m.prefix, m.name);
            self.mapped(&line, m.file, m.start, m.len, false);
        }
        for (_, c) in &ns.children {
            self.emit_canon(*c);
        }
        if id != 0 {
            self.raw("}\n");
        }
    }

    /// A file's hidden module tree, holding its real items.
    fn emit_file(&mut self, f: usize) {
        self.raw(&format!("mod {} {{\n#[allow(unused_imports)]\nuse super::*;\n", file_mod(f)));
        self.emit_file_items(f, 0);
        self.emit_file_children(f, 0);
        self.raw("}\n");
    }

    fn emit_file_children(&mut self, f: usize, id: usize) {
        let p = self.p;
        for (_, c) in &p.nss[id].children {
            if self.present[f][*c] {
                self.emit_file_ns(f, *c);
            }
        }
    }

    fn emit_file_items(&mut self, f: usize, id: usize) {
        let p = self.p;
        for it in p.nss[id].items.iter().filter(|it| it.file == f) {
            let file = &p.files[f];
            let inject = if is_root_main(id, it) {
                Some((it.head, "pub(crate) ".to_string()))
            } else if id != 0
                && it.vis == Vis::Priv
                && file.tok(it.head) != "pub"
                && matches!(it.kind.as_str(), "fn" | "struct" | "enum" | "union" | "trait" | "type" | "const" | "static" | "mod" | "use")
            {
                // file-private: visible in this file's whole module tree and nowhere else
                Some((it.head, format!("pub(in crate::{}) ", file_mod(f))))
            } else {
                None
            };
            self.range(f, it.first, it.last, inject);
            self.raw("\n");
        }
    }

    fn emit_file_ns(&mut self, f: usize, id: usize) {
        let p = self.p;
        let ns = &p.nss[id];
        let anchor = ns
            .decls
            .iter()
            .find(|d| d.file == f)
            .or(ns.decls.first())
            .map(|d| (d.file, d.header_start, d.name_end - d.header_start));
        let hdr = format!("#[allow(non_snake_case)]\npub mod {} {{\n", ns.name);
        match anchor {
            Some((af, s, l)) => self.mapped(&hdr, af, s, l, false),
            None => self.raw(&hdr),
        }
        for &(af, a, b) in ns.inner_attrs.iter().filter(|x| x.0 == f) {
            self.range(af, a, b, None);
            self.raw("\n");
        }
        // lexical nesting within the file, then the public surface contributed by other files
        let mut g = String::from("#[allow(unused_imports)]\nuse super::*;\n");
        let local: std::collections::HashSet<String> = ns
            .items
            .iter()
            .filter(|it| it.file == f)
            .flat_map(|it| item_names(it).into_iter().map(|s| s.to_string()).collect::<Vec<_>>())
            .chain(ns.children.iter().filter(|(_, c)| self.present[f][*c]).map(|(n, _)| n.clone()))
            .collect();
        let imports: Vec<String> = self.surface(id).names.into_iter().filter(|n| !local.contains(n)).collect();
        if !imports.is_empty() {
            g.push_str(&format!("#[allow(unused_imports)]\nuse {}::{{{}}};\n", path_str(p, id), imports.join(", ")));
        }
        match anchor {
            Some((af, s, l)) => self.mapped(&g, af, s, l, false),
            None => self.raw(&g),
        }
        self.emit_file_items(f, id);
        self.emit_file_children(f, id);
        self.raw("}\n");
    }

    /// Emit the tokens [a, b) of a file, rewriting `.A.b` paths. `inject` is a token
    /// index and the text (a visibility) inserted before it.
    fn range(&mut self, fid: usize, a: usize, b: usize, inject: Option<(usize, String)>) {
        let p = self.p;
        let f = &p.files[fid];
        let toks = &f.tokens;
        let mut in_use = false;
        let mut t = a;
        while t < b {
            let tok = toks[t];
            let prev_end = if t == 0 { 0 } else { toks[t - 1].end };
            self.copy(fid, prev_end, tok.start);
            if let Some((at, vis)) = &inject {
                if *at == t {
                    self.mapped(vis, fid, tok.start, 0, false);
                }
            }
            if tok.kind == Kind::Punct && f.tok(t) == "." {
                if let Some(chain) = scan_path(p, fid, t, b) {
                    t = self.path(fid, t, &chain, in_use);
                    continue;
                }
            }
            self.copy(fid, tok.start, tok.end);
            if tok.kind == Kind::Ident && f.tok(t) == "use" {
                in_use = true;
            } else if f.tok(t) == ";" {
                in_use = false;
            }
            t += 1;
        }
    }

    fn path(&mut self, fid: usize, dot_t: usize, chain: &[usize], in_use: bool) -> usize {
        let p = self.p;
        let f = &p.files[fid];
        if in_use {
            // `use` only accepts Rust paths (crates, std, ...); namespaces are not importable this way
            let last = *chain.last().expect("non-empty chain");
            let end = f.tokens[last];
            self.diags.push(Diag::error(
                fid,
                f.tokens[dot_t].start,
                end.end,
                "`use` cannot import a namespace (`.Foo`); use a Rust path such as `std::...` or `crate::...`, or mount with `namespace { .Foo }`",
            ));
            self.copy(fid, f.tokens[dot_t].start, end.end);
            return last + 1;
        }
        let names: Vec<&str> = chain.iter().map(|&i| f.tok(i)).collect();
        let r = resolve_path(p, &names, in_use, Some(fid));
        if matches!(r.found.last(), Some(Some(Found::Ns(_)))) && r.consumed == names.len() {
            let tk = f.tokens[*chain.last().expect("non-empty chain")];
            self.diags.push(Diag::error(
                fid,
                tk.start,
                tk.end,
                "a namespace is not a value; name an item inside it, e.g. `.Foo.item`",
            ));
        }
        if let Some((idx, msg, sev)) = &r.problem {
            let tk = f.tokens[chain[*idx]];
            self.diags.push(Diag::new(*sev, fid, tk.start, tk.end, msg.clone()));
        }
        // a private item of this very file is only reachable through the file's hidden tree
        let private_here = r
            .found
            .iter()
            .flatten()
            .find_map(|x| if let Found::Item(n, i) = x { Some(&p.nss[*n].items[*i]) } else { None })
            .map_or(false, |it| it.vis == Vis::Priv && it.file == fid);
        let root = if private_here { format!("crate::{}", file_mod(fid)) } else { "crate".to_string() };
        self.mapped(&root, fid, f.tokens[dot_t].start, 1, false);
        let mut last = dot_t;
        for &ident in chain.iter().take(r.consumed) {
            self.mapped("::", fid, f.tokens[ident - 1].start, 1, false);
            let tk = f.tokens[ident];
            self.copy(fid, tk.start, tk.end);
            last = ident;
        }
        let mut next = last + 1;
        if in_use
            && is_single_dot(&f.text, &f.tokens, next)
            && next + 1 < f.tokens.len()
            && matches!(f.tok(next + 1), "*" | "{")
        {
            self.mapped("::", fid, f.tokens[next].start, 1, false);
            next += 1;
        }
        next
    }
}
